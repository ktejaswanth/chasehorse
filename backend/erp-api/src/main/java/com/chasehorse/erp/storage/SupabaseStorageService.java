package com.chasehorse.erp.storage;

import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.Map;
import java.util.regex.Pattern;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.web.client.RestClient;

import com.chasehorse.erp.common.ApiException;
import com.chasehorse.erp.config.AppProperties;

/**
 * Supabase Storage over its REST API using the SERVICE key. That key is read from the environment,
 * used only from this class, and never logged or returned. NOTE: written against the documented
 * Storage API; it has NOT been exercised against a live project from this build environment.
 */
public class SupabaseStorageService implements StorageService {
    private static final Logger log = LoggerFactory.getLogger(SupabaseStorageService.class);
    /** Paths are generated by the database; this is a defence-in-depth check before any storage call. */
    private static final Pattern SAFE_PATH = Pattern.compile("^tasks/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\\.(jpg|png|webp|heic)$");

    private final String base;
    private final String bucket;
    private final int ttl;
    private final RestClient client;

    public SupabaseStorageService(AppProperties props, RestClient.Builder builder) {
        AppProperties.Supabase sb = props.supabase();
        this.base = sb.baseUrl() + "/storage/v1";
        this.bucket = sb.evidenceBucket();
        this.ttl = sb.signedUrlSeconds() > 0 ? sb.signedUrlSeconds() : 600;
        SimpleClientHttpRequestFactory rf = new SimpleClientHttpRequestFactory();
        rf.setConnectTimeout(5_000);
        rf.setReadTimeout(30_000);
        this.client = builder.requestFactory(rf)
                .defaultHeader("Authorization", "Bearer " + sb.serviceKey())
                .defaultHeader("apikey", sb.serviceKey())
                .build();
    }

    @Override
    public boolean isConfigured() {
        return true;
    }

    private static String checked(String path) {
        if (path == null || !SAFE_PATH.matcher(path).matches()) {
            throw new IllegalArgumentException("unsafe storage path");
        }
        return path;
    }

    @Override
    @SuppressWarnings("unchecked")
    public SignedUpload createSignedUpload(String path) {
        checked(path);
        try {
            Map<String, Object> res = client.post().uri(URI.create(base + "/object/upload/sign/" + bucket + "/" + path))
                    .retrieve().body(Map.class);
            if (res == null || res.get("url") == null || res.get("token") == null) {
                throw ApiException.unavailable("Storage did not return an upload URL.");
            }
            String url = String.valueOf(res.get("url"));
            return new SignedUpload(url.startsWith("http") ? url : base + url, String.valueOf(res.get("token")), ttl);
        } catch (ApiException e) {
            throw e;
        } catch (RuntimeException e) {
            log.error("Storage: creating signed upload URL failed", e);
            throw ApiException.unavailable("Storage is temporarily unavailable.");
        }
    }

    @Override
    @SuppressWarnings("unchecked")
    public String createSignedDownloadUrl(String path, int seconds) {
        checked(path);
        try {
            Map<String, Object> res = client.post().uri(URI.create(base + "/object/sign/" + bucket + "/" + path))
                    .body(Map.of("expiresIn", Math.min(Math.max(seconds, 30), 3600)))
                    .retrieve().body(Map.class);
            if (res == null || res.get("signedURL") == null) {
                throw ApiException.unavailable("Storage did not return a download URL.");
            }
            String url = String.valueOf(res.get("signedURL"));
            return url.startsWith("http") ? url : base + url;
        } catch (ApiException e) {
            throw e;
        } catch (RuntimeException e) {
            log.error("Storage: creating signed download URL failed", e);
            throw ApiException.unavailable("Storage is temporarily unavailable.");
        }
    }

    @Override
    public ObjectFacts inspect(String path, long maxBytes) {
        checked(path);
        try {
            return client.get().uri(URI.create(base + "/object/authenticated/" + bucket + "/" + path))
                    .exchange((req, res) -> {
                        if (res.getStatusCode().value() == 404 || res.getStatusCode().value() == 400) {
                            throw ApiException.invalid("The file has not been uploaded yet.");
                        }
                        if (!res.getStatusCode().is2xxSuccessful()) {
                            throw ApiException.unavailable("Storage is temporarily unavailable.");
                        }
                        return measure(res.getBody(), maxBytes);
                    });
        } catch (ApiException e) {
            throw e;
        } catch (RuntimeException e) {
            log.error("Storage: reading object failed", e);
            throw ApiException.unavailable("Storage is temporarily unavailable.");
        }
    }

    static ObjectFacts measure(InputStream in, long maxBytes) throws IOException {
        try (in) {
            MessageDigest sha = MessageDigest.getInstance("SHA-256");
            byte[] buf = new byte[8192];
            byte[] head = new byte[32];
            int headLen = 0;
            long total = 0;
            int n;
            while ((n = in.read(buf)) > 0) {
                if (headLen < head.length) {
                    int c = Math.min(n, head.length - headLen);
                    System.arraycopy(buf, 0, head, headLen, c);
                    headLen += c;
                }
                total += n;
                if (total > maxBytes) {
                    throw ApiException.invalid("The file is larger than the allowed " + (maxBytes / (1024 * 1024)) + " MB.");
                }
                sha.update(buf, 0, n);
            }
            if (total == 0) {
                throw ApiException.invalid("The uploaded file is empty.");
            }
            return new ObjectFacts(total, HexFormat.of().formatHex(sha.digest()), java.util.Arrays.copyOf(head, headLen));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    @Override
    public void delete(String path) {
        checked(path);
        try {
            client.delete().uri(URI.create(base + "/object/" + bucket + "/" + path)).retrieve().toBodilessEntity();
        } catch (RuntimeException e) {
            log.warn("Storage: deleting rejected object failed", e);
        }
    }
}
